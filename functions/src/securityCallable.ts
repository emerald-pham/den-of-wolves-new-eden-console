export function rejectClientRandomOutcome(callableName: string, data: unknown): void {
  if (!SERVER_RANDOM_CALLABLES.has(callableName) || !data || typeof data !== 'object' || Array.isArray(data)) return;
  if (Object.keys(data).some(key => CLIENT_OUTCOME_FIELDS.has(key))) {
    throw new HttpsError('invalid-argument', 'Random outcomes are generated by the server.');
  }
}

/**
 * Keep Firebase's callable transport and Auth/App Check verification. Supply canonical
 * defaults explicitly because re-exported modules may construct handlers before index
 * initialization applies global options; each callable's explicit overrides still win.
 * Platform verification denials occur before this handler and retain Firebase's private,
 * category-only callable-request-verification logs. Application denials add this safe record.
 */
// Match the SDK's request/return generic defaults so existing callable declarations retain their types.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function auditedOnCall<T = any, R = any>(
  callableName: string,
  handler: (request: CallableRequest<T>, response?: CallableResponse<unknown>) => R,
) : ReturnType<typeof onCall<T, Promise<R>>>;
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function auditedOnCall<T = any, R = any>(
  callableName: string,
  options: CallableOptions<T>,
  handler: (request: CallableRequest<T>, response?: CallableResponse<unknown>) => R,
) : ReturnType<typeof onCall<T, Promise<R>>>;
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function auditedOnCall<T = any, R = any>(
  callableName: string,
  optionsOrHandler: CallableOptions<T> | ((request: CallableRequest<T>, response?: CallableResponse<unknown>) => R),
  optionalHandler?: (request: CallableRequest<T>, response?: CallableResponse<unknown>) => R,
) {
  if (!/^[A-Za-z][\w]{0,99}$/.test(callableName)) throw new TypeError('Invalid callable name.');
  const handler = typeof optionsOrHandler === 'function' ? optionsOrHandler : optionalHandler;
  if (!handler) throw new TypeError('A callable handler is required.');
  const boundary = async (request: CallableRequest<T>, response?: CallableResponse<unknown>): Promise<R> => {
    try {
      // Preserve each producer's unauthenticated response before its schema boundary.
      if (request.auth?.uid) rejectClientRandomOutcome(callableName, request.data);
      return await handler(request, response);
    } catch (error) {
      const record = buildSecurityDenialRecord(callableName, request, error);
      if (record) {
        // Observability must never replace the original authorization/error contract.
        try { warn('Callable security denial', record); } catch { /* Preserve the original failure. */ }
      }
      throw error;
    }
  };
  return onCall<T, Promise<R>>({
    ...CALLABLE_RUNTIME_OPTIONS,
    ...(typeof optionsOrHandler === 'function' ? {} : optionsOrHandler),
  }, boundary);
}
