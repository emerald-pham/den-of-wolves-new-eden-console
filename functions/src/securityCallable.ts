import { createHash } from 'node:crypto';
import { warn } from 'firebase-functions/logger';
import { HttpsError, onCall, type CallableOptions, type CallableRequest, type CallableResponse } from 'firebase-functions/v2/https';
import { CALLABLE_RUNTIME_OPTIONS } from './runtimeOptions';

const DENIAL_CATEGORIES = {
  unauthenticated: 'auth', 'permission-denied': 'authorization',
  'invalid-argument': 'schema', 'resource-exhausted': 'rate-limit',
} as const;

export type SecurityDenialRecord = Readonly<{
  type: 'security-denial'; schemaVersion: 1; callableName: string;
  code: keyof typeof DENIAL_CATEGORIES;
  category: typeof DENIAL_CATEGORIES[keyof typeof DENIAL_CATEGORIES];
  actorHash?: string; sessionHash?: string; requestHash?: string;
  redactionPolicy: 'security-denial-hashed-metadata-v1';
}>;

type DenialRequest = Readonly<{ auth?: Readonly<{ uid: string }>; data?: unknown }>;

function hashIdentifier(value: unknown, kind: string): string | undefined {
  if (typeof value !== 'string' || !/^[\w-]{1,128}$/.test(value)) return undefined;
  return createHash('sha256').update(`security-denial-${kind}\0${value}`).digest('hex');
}

/** No payload values, credentials, headers, error prose, names, or addresses enter this record. */
export function buildSecurityDenialRecord(
  callableName: string, request: DenialRequest, error: unknown,
): SecurityDenialRecord | undefined {
  if (!/^[A-Za-z][\w]{0,99}$/.test(callableName)) throw new TypeError('Invalid callable name.');
  if (!(error instanceof HttpsError) || !Object.hasOwn(DENIAL_CATEGORIES, error.code)) return undefined;
  const code = error.code as keyof typeof DENIAL_CATEGORIES;
  const data = request.data && typeof request.data === 'object' && !Array.isArray(request.data)
    ? request.data as Record<string, unknown> : {};
  const actorHash = hashIdentifier(request.auth?.uid, 'actor');
  const sessionHash = hashIdentifier(data.sessionId, 'session');
  const requestHash = hashIdentifier(data.requestId, 'request');
  return {
    type: 'security-denial', schemaVersion: 1, callableName, code, category: DENIAL_CATEGORIES[code],
    ...(actorHash ? { actorHash } : {}), ...(sessionHash ? { sessionHash } : {}),
    ...(requestHash ? { requestHash } : {}), redactionPolicy: 'security-denial-hashed-metadata-v1',
  };
}

